#!/usr/bin/env python3
"""mkfont-rs.py - export the Facet font's glyph outlines to Rust for the browser.

Facet is defined once, in tools/mkfont.py, as polylines on a 4 x 10 grid;
mkfont.py rasterizes them into include/font_data.h at three fixed sizes for
the kernel. The browser needs any size, bold and italic, so it takes the
outlines themselves and rasterizes them with the same geometry
(runner/browser/src/font.rs; a unit test checks that its 8x16 rendering
matches font_data.h's font_small).

Usage: tools/mkfont-rs.py > runner/browser/src/font_data.rs
"""
import ast
import os

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "mkfont.py"), encoding="utf-8").read()
glyphs = None
for node in ast.parse(src).body:
    if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "GLYPHS" for t in node.targets):
        glyphs = ast.literal_eval(node.value)
assert glyphs, "GLYPHS not found in mkfont.py"


def rust_char(c):
    if c == "'" or c == "\\":
        return "'\\" + c + "'"
    if c.isascii():
        return "'" + c + "'"
    return "'\\u{%04X}'" % ord(c)


print("// Generated by tools/mkfont-rs.py from tools/mkfont.py: the outlines of")
print("// æther's Facet font (an original design). Do not edit by hand.")
print("//")
print("// Each glyph is polylines separated by '|', points \"x,y\" on a 4 x 10 grid:")
print("// x 0..4, cap height y 1..7, x-height y 3, baseline y 7, descender y 9.")
print("pub static FACET: &[(char, &str)] = &[")
for c in sorted(glyphs, key=ord):
    assert '"' not in glyphs[c] and "\\" not in glyphs[c]
    print(f"    ({rust_char(c)}, \"{glyphs[c]}\"),")
print("];")

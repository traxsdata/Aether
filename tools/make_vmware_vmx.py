"""Generate a diskless Workstation 17+ UEFI VM, with diagnostic serial capture."""

from __future__ import annotations

import os
import sys
from pathlib import Path

from boot_support import find_iso

ROOT = Path(__file__).resolve().parent.parent


def vmx_string(value: str) -> str:
    # VMX quoted strings use |HH escapes. Reject control characters rather than
    # allowing a host path to inject another VMX setting.
    if any(ord(character) < 32 or ord(character) == 127 for character in value):
        raise ValueError("VMX paths cannot contain control characters")
    return value.replace("|", "|7C").replace('"', "|22")


def render(iso: Path, build: Path) -> str:
    return f'''# Generated by tools/make-vmware-vmx.sh; no installed disk is used.
.encoding = "UTF-8"
config.version = "8"
virtualHW.version = "20"
displayName = "Aether"
guestOS = "other-64"
firmware = "efi"
uefi.secureBoot.enabled = "FALSE"
memsize = "2048"
numvcpus = "2"
cpuid.coresPerSocket = "2"

ide1:0.present = "TRUE"
ide1:0.deviceType = "cdrom-image"
ide1:0.fileName = "{vmx_string(str(iso))}"
ide1:0.startConnected = "TRUE"
ide1:0.autodetect = "FALSE"

ethernet0.present = "FALSE"
sound.present = "FALSE"
usb.present = "FALSE"
ehci.present = "FALSE"
usb_xhci.present = "FALSE"
mouse.vusb.enable = "FALSE"
vmmouse.present = "FALSE"
keyboard.vusb.enable = "FALSE"

svga.autodetect = "FALSE"
svga.vramSize = "134217728"
svga.maxWidth = "1920"
svga.maxHeight = "1200"
mks.enable3d = "FALSE"
mks.enableVulkan = "FALSE"

# Preserve boot evidence even if the graphical desktop fails.
serial0.present = "TRUE"
serial0.fileType = "file"
serial0.fileName = "{vmx_string(str(build / 'aether-vmware-serial.log'))}"
serial0.startConnected = "TRUE"
'''


def main() -> int:
    build = Path(os.environ.get("BUILD", str(ROOT / "build"))).resolve()
    try:
        iso = find_iso(build, os.environ.get("AETHER_ISO"))
        content = render(iso, build)
        build.mkdir(parents=True, exist_ok=True)
        vmx = build / "aether-vmware.vmx"
        vmx.write_text(content, encoding="utf-8")
        print(vmx)
        return 0
    except (OSError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())

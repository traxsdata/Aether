"""Generate the terminal's 8x16 bitmap font from a Spleen BDF file.

Usage: tools/gen-terminal-font.py spleen-8x16.bdf > kernel/term/src/font.rs

Spleen is BSD-2-Clause (see kernel/term/FONT-LICENSE). Only printable ASCII
and the few block and box-drawing glyphs the terminal maps are emitted, so the
kernel image carries about 2 KiB of font data.
"""

from __future__ import annotations

import sys

# Internal glyph codes above ASCII, in the order `aether_term::glyph_code`
# assigns them. Keep the two lists in sync.
EXTRA = [
    0x2588,  # full block
    0x2591,  # light shade
    0x2592,  # medium shade
    0x2593,  # dark shade
    0x2500,  # light horizontal
    0x2502,  # light vertical
    0x250C,  # down and right
    0x2510,  # down and left
    0x2514,  # up and right
    0x2518,  # up and left
    0x251C,  # vertical and right
    0x2524,  # vertical and left
    0x252C,  # down and horizontal
    0x2534,  # up and horizontal
    0x253C,  # vertical and horizontal
    0x25B2,  # up triangle
    0x25BC,  # down triangle
    0x00B7,  # middle dot
]


def parse(path: str) -> dict[int, list[int]]:
    glyphs: dict[int, list[int]] = {}
    encoding = None
    rows: list[int] | None = None
    bbx = (8, 16, 0, -4)
    with open(path, encoding="latin-1") as handle:
        for line in handle:
            parts = line.split()
            if not parts:
                continue
            if parts[0] == "ENCODING":
                encoding = int(parts[1])
            elif parts[0] == "BBX":
                bbx = tuple(int(value) for value in parts[1:5])
            elif parts[0] == "BITMAP":
                rows = []
            elif parts[0] == "ENDCHAR":
                if encoding is not None and rows is not None:
                    width, height, _x, y = bbx
                    # Place the glyph in the 16-row cell: baseline at row 12.
                    top = 12 - (height + y)
                    cell = [0] * 16
                    for index, value in enumerate(rows):
                        row = top + index
                        if 0 <= row < 16:
                            cell[row] = value
                    glyphs[encoding] = cell
                encoding = None
                rows = None
            elif rows is not None:
                rows.append(int(parts[0], 16) & 0xFF)
    return glyphs


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    glyphs = parse(sys.argv[1])
    codes = list(range(0x20, 0x7F)) + EXTRA
    print("// SPDX-License-Identifier: BSD-2-Clause")
    print("// Generated by tools/gen-terminal-font.py from Spleen 8x16 2.1.0.")
    print("// Copyright (c) 2018-2024, Frederic Cambus. See kernel/term/FONT-LICENSE.")
    print("//! 8x16 terminal glyphs: printable ASCII, then the extra glyphs.")
    print()
    print(f"/// Number of glyphs in [`GLYPHS`].")
    print(f"pub const GLYPH_COUNT: usize = {len(codes)};")
    print()
    print("/// One byte per row, most significant bit leftmost.")
    print("#[rustfmt::skip]")
    print("pub static GLYPHS: [[u8; 16]; GLYPH_COUNT] = [")
    for code in codes:
        cell = glyphs.get(code, [0] * 16)
        values = ", ".join(f"0x{value:02x}" for value in cell)
        label = chr(code) if 0x20 < code < 0x7F else f"U+{code:04X}"
        print(f"    [{values}], // {label}")
    print("];")
    return 0


if __name__ == "__main__":
    sys.exit(main())

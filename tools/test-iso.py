"""Boot the generated El Torito ISO under UEFI and require the desktop markers.

The FAT-image boot test proves the kernel; this test proves the *distribution
artifact*. It exercises the same El Torito path VMware Workstation uses when an
ISO is attached to a UEFI virtual machine.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "build"
ISO_DIR = BUILD / "ISOs"
SERIAL = BUILD / "serial-iso.log"
VARS = BUILD / "OVMF_VARS_ISO_TEST.fd"
TIMEOUT = int(os.environ.get("AETHER_ISO_TIMEOUT", "120"))

# The ISO path is generated by the ISO target; allow an explicit override for
# release qualification or a manually attached image.
ISO = Path(os.environ["AETHER_ISO"]) if os.environ.get("AETHER_ISO") else None


def find_iso() -> Path:
    if ISO is not None:
        return ISO
    images = sorted(ISO_DIR.glob("*.iso"), key=lambda path: path.stat().st_mtime)
    if not images:
        raise SystemExit("error: no ISO under build/ISOs; run `make iso`")
    return images[-1]


CODE_CANDIDATES = (
    Path("/usr/share/OVMF/OVMF_CODE_4M.fd"),
    Path("/usr/share/OVMF/OVMF_CODE.fd"),
    Path("/usr/share/edk2/ovmf/OVMF_CODE.fd"),
    Path("/usr/share/edk2/ovmf/OVMF_CODE_4M.fd"),
    Path("/usr/share/qemu/OVMF.fd"),
)
VARS_CANDIDATES = (
    Path("/usr/share/OVMF/OVMF_VARS_4M.fd"),
    Path("/usr/share/OVMF/OVMF_VARS.fd"),
    Path("/usr/share/edk2/ovmf/OVMF_VARS.fd"),
    Path("/usr/share/edk2/ovmf/OVMF_VARS_4M.fd"),
)

REQUIRED = (
    "AETHER_LOADER_OK",
    "AETHER_KERNEL_OK",
    "AETHER_BOOT_OK",
    "AETHER_GRAPHICS_OK",
    "AETHER_DESKTOP_OK",
    "AETHER_WM_OK",
    "AETHER_POINTER_OK",
    "AETHER_SHELL_OK",
)
FAILURES = (
    "AETHER_LOADER_FAILED",
    "AETHER_LOADER_PANIC",
    "AETHER_KERNEL_PANIC",
    "AETHER_BOOT_FAILED",
    "AETHER_WM_FAILED",
    "AETHER_POINTER_FAILED",
)


def find_firmware() -> tuple[Path, Path | None]:
    code_env = os.environ.get("OVMF_CODE")
    vars_env = os.environ.get("OVMF_VARS")
    if code_env:
        return Path(code_env), Path(vars_env) if vars_env else None
    code = next((path for path in CODE_CANDIDATES if path.exists()), None)
    if code is None:
        raise SystemExit("error: OVMF firmware not found; set OVMF_CODE and OVMF_VARS")
    variables = next((path for path in VARS_CANDIDATES if path.exists()), None)
    return code, variables


def main() -> int:
    try:
        iso = find_iso()
    except SystemExit as error:
        print(error, file=sys.stderr)
        return 2
    if not iso.exists():
        print(f"error: ISO not found: {iso}", file=sys.stderr)
        return 2

    code, variables = find_firmware()
    BUILD.mkdir(exist_ok=True)
    SERIAL.unlink(missing_ok=True)

    command = [
        "qemu-system-x86_64",
        "-machine",
        "q35,accel=tcg",
        "-cpu",
        "max",
        "-m",
        "1024M",
        "-display",
        "vnc=127.0.0.1:11",
        "-device",
        "VGA",
        "-monitor",
        "none",
        "-no-reboot",
        "-serial",
        f"file:{SERIAL}",
        "-boot",
        "d",
        "-cdrom",
        str(iso),
    ]
    if variables is None:
        command += ["-bios", str(code)]
    else:
        shutil.copyfile(variables, VARS)
        command += [
            "-drive",
            f"if=pflash,format=raw,readonly=on,file={code}",
            "-drive",
            f"if=pflash,format=raw,file={VARS}",
        ]

    process = subprocess.Popen(
        command, stdout=subprocess.DEVNULL, stderr=subprocess.STDOUT
    )
    deadline = time.monotonic() + TIMEOUT
    try:
        while time.monotonic() < deadline:
            if process.poll() is not None:
                break
            log = SERIAL.read_text(errors="replace") if SERIAL.exists() else ""
            if any(marker in log for marker in FAILURES):
                print(log)
                print("FAIL: ISO boot reported an error", file=sys.stderr)
                return 1
            if all(marker in log for marker in REQUIRED):
                print(log)
                print(f"PASS: ISO {iso.name} boots the Aether desktop under UEFI")
                return 0
            time.sleep(0.25)
        print(SERIAL.read_text(errors="replace") if SERIAL.exists() else "")
        print(
            f"FAIL: timed out after {TIMEOUT}s waiting for {REQUIRED}",
            file=sys.stderr,
        )
        return 1
    finally:
        process.terminate()
        try:
            process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait()


if __name__ == "__main__":
    sys.exit(main())

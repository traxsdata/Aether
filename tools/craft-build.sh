#!/bin/sh
# craft-build.sh - build a Craft app (or any eframe app) as a static musl
# binary that draws through æther's runner (runner/eframe).
#
#   tools/craft-build.sh <repo-dir> <shell-or-bin-crate> <out.elf>
#
# <shell-or-bin-crate> is either the name of a shell in tools/craft-shells/
# (e.g. gridcraft: a tiny main.rs that creates the app the way its -web
# crate does) or the path of a binary crate to build as it is.
#
# A shell is generated as its own crate outside the app repo, in
# $CRAFT_WORK (default /tmp/craft-build/<name>); its Cargo.toml lists the
# `//! deps:` lines of the shell (with @REPO@ replaced), applies
# [patch.crates-io] eframe = runner/eframe, and repeats the repo's own
# [patch.*] tables, since patches only apply from the workspace root.
# The repo's Cargo.lock is copied in so the same versions are used.
# A binary crate is built in place with the patch given on the command line
# (`--config`); its Cargo.lock is put back afterwards.
#
# CRAFT_TARGET (default x86_64-unknown-linux-musl) picks the target; set it
# to "host" for a native build to run headless tests against.
set -eu

if [ $# -ne 3 ]; then
    echo "usage: $0 <repo-dir> <shell-name|bin-crate-dir> <out.elf>" >&2
    exit 2
fi
REPO=$(cd "$1" && pwd)
WHAT=$2
OUT=$3
TOOLS=$(cd "$(dirname "$0")" && pwd)
RUNNER=$(cd "$TOOLS/../runner" && pwd)
TARGET=${CRAFT_TARGET:-x86_64-unknown-linux-musl}

if [ "$TARGET" = host ]; then
    TARGET_ARGS=""
    TARGET_DIR_PART=""
else
    TARGET_ARGS="--target $TARGET"
    TARGET_DIR_PART="$TARGET/"
    # Static PIE, no libc.so at run time.
    export RUSTFLAGS="${RUSTFLAGS:-} -C target-feature=+crt-static"
fi

if [ -f "$TOOLS/craft-shells/$WHAT.rs" ]; then
    NAME=$WHAT
    WORK=${CRAFT_WORK:-/tmp/craft-build/$NAME}
    mkdir -p "$WORK/src"
    cp "$TOOLS/craft-shells/$NAME.rs" "$WORK/src/main.rs"
    python3 -I - "$REPO" "$TOOLS/craft-shells/$NAME.rs" "$RUNNER" "$WORK" "$NAME" <<'PY'
import sys, tomllib, os
repo, shell, runner, work, name = sys.argv[1:]
deps, features = [], ["default_fonts"]
for line in open(shell, encoding="utf-8"):
    if line.startswith("//! deps:"):
        deps.append(line[len("//! deps:"):].strip().replace("@REPO@", repo))
    elif line.startswith("//! eframe:"):
        features = [f.strip() for f in line[len("//! eframe:"):].split(",") if f.strip()]

def val(v, base):
    # TOML inline value, with relative paths made absolute against `base`.
    if isinstance(v, dict):
        items = []
        for k, x in v.items():
            if k == "path":
                x = os.path.normpath(os.path.join(base, x))
            items.append(f"{k} = {val(x, base)}")
        return "{ " + ", ".join(items) + " }"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "[" + ", ".join(val(x, base) for x in v) + "]"
    return str(v)

ws = tomllib.load(open(os.path.join(repo, "Cargo.toml"), "rb"))
patches = ws.get("patch", {})
crates_io = dict(patches.get("crates-io", {}))
crates_io["eframe"] = {"path": os.path.join(runner, "eframe")}
out = [
    "# Generated by tools/craft-build.sh; edits are overwritten.",
    "[package]",
    f'name = "{name}-aether"',
    'version = "0.1.0"',
    'edition = "2024"',
    "publish = false",
    "",
    "[[bin]]",
    f'name = "{name}"',
    'path = "src/main.rs"',
    "",
    "[dependencies]",
    'eframe = { version = "0.36", default-features = false, features = [' + ", ".join(f'"{f}"' for f in features) + "] }",
    *deps,
    "",
    "[workspace]",
    "",
]
for source, table in [("crates-io", crates_io)] + [(s, t) for s, t in patches.items() if s != "crates-io"]:
    key = source if source == "crates-io" else f'"{source}"'
    out.append(f"[patch.{key}]")
    for k, v in table.items():
        out.append(f"{k} = {val(v, repo)}")
    out.append("")
prof = ws.get("profile", {}).get("release", {})
out += ["[profile.release]", f'opt-level = {val(prof.get("opt-level", 3), repo)}', 'lto = "thin"', "codegen-units = 16", "debug = 0", ""]
open(os.path.join(work, "Cargo.toml"), "w", encoding="utf-8").write("\n".join(out))
PY
    if [ ! -f "$WORK/Cargo.lock" ] && [ -f "$REPO/Cargo.lock" ]; then
        cp "$REPO/Cargo.lock" "$WORK/Cargo.lock"
    fi
    # The repo's lock pins the real eframe; move just that package to the patch.
    (cd "$WORK" && cargo update -p eframe --offline 2>/dev/null || cargo update -p eframe)
    echo "craft-build: building $NAME in $WORK for $TARGET" >&2
    # shellcheck disable=SC2086
    (cd "$WORK" && cargo build --release $TARGET_ARGS)
    BIN="$WORK/target/${TARGET_DIR_PART}release/$NAME"
else
    CRATE=$(cd "$WHAT" && pwd)
    NAME=$(cd "$CRATE" && cargo metadata --no-deps --format-version 1 |
        python3 -I -c 'import json,sys,os; d=json.load(sys.stdin); c=os.getcwd(); p=[p for p in d["packages"] if os.path.dirname(p["manifest_path"])==c][0]; print([t["name"] for t in p["targets"] if "bin" in t["kind"]][0])')
    WORK=${CRAFT_WORK:-/tmp/craft-build/$NAME}
    mkdir -p "$WORK"
    LOCK=$(cd "$CRATE" && cargo locate-project --workspace --message-format plain | sed 's/Cargo.toml$/Cargo.lock/')
    [ -f "$LOCK" ] && cp "$LOCK" "$WORK/Cargo.lock.orig"
    echo "craft-build: building $NAME from $CRATE for $TARGET" >&2
    # shellcheck disable=SC2086
    status=0
    (cd "$CRATE" && cargo build --release $TARGET_ARGS --target-dir "$WORK/target" --bin "$NAME" \
        --config "patch.crates-io.eframe.path=\"$RUNNER/eframe\"") || status=$?
    [ -f "$WORK/Cargo.lock.orig" ] && cp "$WORK/Cargo.lock.orig" "$LOCK"
    [ $status -eq 0 ] || exit $status
    BIN="$WORK/target/${TARGET_DIR_PART}release/$NAME"
fi

mkdir -p "$(dirname "$OUT")"
cp "$BIN" "$OUT"
ls -l "$OUT" >&2
